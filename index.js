//ФУНКЦИИ 
function ask(text) {
    const answer = prompt(text);
    return answer === null ? "0" : answer; 
}

function randomInt(min, max) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
}

function countItem(name) {
    return inventory.filter(function (item) {
        return item === name;
    }).length;
}

function getStatus() {
    return "HP: " + playerHp + "/" + MAX_HP +
        " | Монеты: " + coins +
        " | Оружие: " + weapon +
        " | Щит: " + (shieldOn ? "надет" : "нет");
}

function showInventory() {
    if (inventory.length === 0) {
        alert("Рюкзак пуст.\n\n" + getStatus());
    } else {
        alert("В рюкзаке: " + inventory.join(", ") + "\n\n" + getStatus());
    }
}

// ИНВЕНТАРЬ
function useInventory() {
    while (true) {
        const choice = ask(
            "ИНВЕНТАРЬ\n" + getStatus() + "\n" +
            "В рюкзаке: " + (inventory.length ? inventory.join(", ") : "пусто") + "\n\n" +
            "1 — Взять меч\n" +
            "2 — Взять топор\n" +
            "3 — Надеть щит\n" +
            "4 — Съесть магическую траву\n" +
            "0 — Закрыть"
        );

        if (choice === "0") {
            return false;
        } else if (choice === "1") {
            if (inventory.includes("меч")) {
                weapon = "меч";
                alert("Вы взяли меч в руки (урон 20–30).");
                return true;
            }
            alert("У вас нет меча.");
        } else if (choice === "2") {
            if (inventory.includes("топор")) {
                weapon = "топор";
                alert("Вы взяли топор в руки (урон 30).");
                return true;
            }
            alert("У вас нет топора.");
        } else if (choice === "3") {
            if (!inventory.includes("щит")) {
                alert("У вас нет щита.");
            } else if (shieldOn) {
                alert("Щит уже надет.");
            } else {
                shieldOn = true;
                alert("Вы надели щит. Урон по вам уменьшен на 20.");
                return true;
            }
        } else if (choice === "4") {
            if (!inventory.includes("магическая трава")) {
                alert("У вас нет магической травы.");
            } else if (playerHp === MAX_HP) {
                alert("Вы и так полностью здоровы.");
            } else {
                inventory.splice(inventory.indexOf("магическая трава"), 1);
                playerHp = MAX_HP;
                alert("Трава восстановила здоровье до " + MAX_HP + " HP!");
                return true;
            }
        } else {
            alert("Такого действия нет.");
        }
    }
}

