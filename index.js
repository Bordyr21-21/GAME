// Бой с боссом.
function fightBoss() {
    let bossHp = 550;
    let turn = 0;

    alert("Вы открыли дверь ключом. В зале вас ждёт Хранитель!\nНачинается битва!");

    while (true) {
        const choice = ask(
            "БИТВА С ХРАНИТЕЛЕМ\n" +
            "Хранитель: " + bossHp + " HP\n" +
            getStatus() + "\n\n" +
            "1 — Атаковать\n" +
            "2 — Инвентарь (действие занимает ход)"
        );

        let acted = false;

        if (choice === "1") {
            let damage;
            if (weapon === "меч") {
                damage = randomInt(20, 30);
            } else if (weapon === "топор") {
                damage = 30;
            } else {
                damage = randomInt(5, 10);
            }
            bossHp -= damage;
            alert("Вы нанесли " + damage + " урона.");
            acted = true;
        } else if (choice === "2") {
            acted = useInventory();
        } else {
            alert("Нужно выбрать 1 или 2. Из боя не сбежать!");
        }

        if (!acted) {
            continue;
        }

        if (bossHp <= 0) {
            return "победа";
        }

        turn++;

        // Босс бьёт раз в три хода
        if (turn % 3 === 0) {
            let bossDamage = 45;
            if (shieldOn) {
                bossDamage -= 20;
            }
            playerHp -= bossDamage;
            alert("Хранитель атакует! Вы получили " + bossDamage + " урона.");

            if (playerHp <= 0) {
                return "поражение";
            }
        }
    }
}

